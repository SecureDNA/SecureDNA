#[derive(Debug, Clone)]
pub enum QueryError {
    WrongSizeResponse,
    MissingKeyserverResponse,
    InvalidRistrettoPoint(DecodeError),
    ValidationFailed(Vec<KeyserverId>),
}

impl std::error::Error for QueryError {}

impl fmt::Display for QueryError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            QueryError::WrongSizeResponse => {
                write!(f, "Query response has the wrong size")
            }
            QueryError::InvalidRistrettoPoint(err) => {
                write!(
                    f,
                    "Invalid ristretto point returned from keyservers: {err:?}"
                )
            }
            QueryError::ValidationFailed(keyservers) => {
                write!(
                    f,
                    "Query response did not validate. Responsible keyservers: {:?}",
                    keyservers
                )
            }
            QueryError::MissingKeyserverResponse => {
                write!(f, "Missing keyserver response")
            }
        }
    }
}

/// Holds information necessary to reconstitute keyserver responses into completed hashes.
#[derive(Clone)]
pub struct QueriesSecurityContext {
    num_windows: usize,
    verifier: Verifier,
    blinder: Blinder,
}

/// Builds [`CompressedQuery`]s from windows.
///
/// Given an iterator of windows, this function hashes and blinds the windows, converting them
/// into an `Arc<[CompressedQuery]>`, which is returned along with a [`QueriesSecurityContext`].
/// The [`QueriesSecurityContext`] may be used to recombine keyserver responses into
/// [`Vec<CompressedCompletedHashValue>`]s.
///
/// `padding` is the number of random windows to add to the returned `Arc<[CompressedQuery]>`.
/// Padding should be used to increase the total number of windows to at least 100 or so,
/// in order to avoid timing attacks related to hash verification. (see [`Verifier`] for details)
///
/// `security_strength` controls how strong verification is; it's just passed to [`Verifier`].
pub fn setup_queries<WI>(
    mut rng: impl CryptoRng + RngCore,
    windows: WI,
    padding: usize,
    security_strength: u8,
) -> (Arc<[CompressedQuery]>, QueriesSecurityContext)
where
    WI: IntoIterator<Item: AsRef<[u8]>>,
{
    let windows = windows.into_iter();
    // If these are smaller than the actual iter... oh well, we'll reallocate
    // If they're too big... that's really a programming error; we'll let Vec deal with that
    let (min_windows, max_windows) = windows.size_hint();
    let num_windows = max_windows.unwrap_or(min_windows);
    let num_rps = num_windows.saturating_add(padding).saturating_add(1);
    let mut rps = Vec::with_capacity(num_rps);
    rps.extend(windows.map(|w| RistrettoPoint::hash_from_bytes::<Sha3_512>(w.as_ref())));
    rps.extend((0..padding).map(|_| RistrettoPoint::random(&mut rng)));

    let (balancer, verifier) = Verifier::balancer_and_verifier(&mut rng, security_strength, &rps);
    rps.push(balancer);
    let blinder = Blinder::from_blinding_in_place(&mut rng, &mut rps);

    let queries = rps.into_iter().map(CompressedQuery::from_rp).collect();
    let security_context = QueriesSecurityContext {
        num_windows,
        verifier,
        blinder,
    };
    (queries, security_context)
}

impl QueriesSecurityContext {
    /// Recombines keyserver responses into [`Vec<CompressedCompletedHashValue>`].
    ///
    /// The query responses must be [`Vec<CompressedCompletedHashValue>`]s generated by scaling
    /// [`setup_queries`]'s `Arc<[CompressedQuery]>` by a value compatible with the given
    /// [`ActiveSecurityKey`].
    ///
    /// If the number of responses differs from the [`ActiveSecurityKey`]'s quorum size, this
    /// will return [`QueryError::MissingKeyserverResponse`]. Note that this also occurs if there
    /// are too many responses.
    ///
    /// If any response contains the wrong number of [`CompressedHashPart`]s, this will return
    /// [`QueryError::WrongSizeResponse`].
    ///
    /// If any [`CompressedHashPart`] cannot be decompressed into valid ristretto point,
    /// this will return [`QueryError::InvalidRistrettoPoint`].
    ///
    /// If the responses don't match the provided [`ActiveSecurityKey`], this will return
    /// [`QueryError::ValidationFailed`].
    pub fn recombine(
        self,
        responses: &[(KeyserverId, Vec<CompressedHashPart>)],
        active_security_key: &ActiveSecurityKey,
    ) -> Result<Vec<CompressedCompletedHashValue>, QueryError> {
        if responses.len() != active_security_key.supported_quorum() {
            return Err(QueryError::MissingKeyserverResponse);
        }
        let expected_len = self.verifier.expected_elements();
        if responses.iter().any(|(_, hp)| hp.len() != expected_len) {
            return Err(QueryError::WrongSizeResponse);
        }
        let keyservers = responses.iter().map(|(ks_id, _)| *ks_id).collect();

        let Self {
            num_windows,
            verifier,
            blinder,
        } = self;
        let blinded_hashes = combined_hashes(responses);
        let rps: Result<Vec<_>, _> = blinder.try_unblinded(blinded_hashes).collect();
        let rps = rps.map_err(QueryError::InvalidRistrettoPoint)?;

        let db_key_commitment = active_security_key.database_key_commitment();
        if verifier.verify(&rps, db_key_commitment).is_err() {
            let bad_keyservers = responses
                .iter()
                .filter_map(|(keyserver, hash_parts)| {
                    let blinded = hash_parts
                        .iter()
                        // NOTE: unwrap won't panic because otherwise `rps?` would have bailed.
                        // Also, can't flatmap because size-hint mismatch angers multiscalar mul.
                        .map(|hash_part| hash_part.to_rp().unwrap());
                    let rps = blinder.unblinded(blinded);
                    let ks_commitment =
                        active_security_key.adjusted_keyserver_commitment(*keyserver, &keyservers);
                    verifier
                        .verify(rps, &ks_commitment)
                        .is_err()
                        .then_some(*keyserver)
                })
                .sorted() // TODO: Should ValidationFailed hold a KeyserverIdSet?
                .collect();
            return Err(QueryError::ValidationFailed(bad_keyservers));
        }

        let completed_hashes = rps
            .into_iter()
            .map(CompressedCompletedHashValue::from_rp)
            .take(num_windows)
            .collect();
        Ok(completed_hashes)
    }
}

// For each query, decompresses and sums its hashparts.
// Note: although we're not actually using the `KeyserverId`s right now, I'm still taking them
// in case we later want to return better diagnostics about which keyserver and hash was invalid.
fn combined_hashes(
    responses: &[(KeyserverId, Vec<CompressedHashPart>)],
) -> impl Iterator<Item = Result<RistrettoPoint, DecodeError>> + use<'_> {
    let mut hashpart_iters: Vec<_> = responses
        .iter()
        .map(|(_ks_id, hash_parts)| hash_parts.iter().map(CompressedHashPart::to_rp))
        .collect();
    // TODO: find way to make proper size hint for better efficiency?
    std::iter::from_fn(move || hashpart_iters.iter_mut().map(Iterator::next).sum())
}

