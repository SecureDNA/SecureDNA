    #[test]
    fn recombine_rejects_invalid_ristrettos() {
        let rng = &mut OsRng;
        let num_required_keyshares = 2..6;
        let num_additional_keys = 0..6;
        let keyshares = KeyShares::random(rng, num_required_keyshares, num_additional_keys);
        let quorum_set = keyshares.random_quorum_set(rng);
        let padding = 0;
        let windows = [""];

        let (queries, security_context) =
            setup_queries(&mut *rng, windows, padding, SECURITY_PARAMETER);
        let mut responses = keyshares.apply_keyshares(&quorum_set, queries.iter().copied());
        let bad_response_i = rng.gen_range(0..responses.len());
        let hashparts = &mut responses[bad_response_i].1;
        let bad_hashpart_i = rng.gen_range(0..hashparts.len());
        corrupt_hashpart(&mut hashparts[bad_hashpart_i]);
        let err = security_context
            .recombine(&responses, &keyshares.active_security_key)
            .unwrap_err();
        assert!(matches!(err, QueryError::InvalidRistrettoPoint(_)));
    }

    #[test]
    fn corrupted_keyservers_cause_query_error_and_are_correctly_identified() {
        let mut rng = OsRng;

        let num_required_keyshares = 2..6;
        let num_additional_keys = 0..6;
        let mut keyshares =
            KeyShares::random(&mut rng, num_required_keyshares, num_additional_keys);
        let quorum_set = keyshares.random_quorum_set(&mut rng);
        let corrupted_ks_set = random_populated_subset(&mut rng, &quorum_set);

        for ks_id in &corrupted_ks_set {
            *keyshares.share_mut(ks_id) = Scalar::random(&mut rng).into();
        }

        let windows = [
            "foobar",
            "The five boxing wizards jump quickly.",
            "",
            "acgtacgtacgt",
            "xyzzy",
        ];
        let padding = 0;

        let result =
            hash_via_keyshares(&mut rng, &keyshares, &quorum_set, padding, windows).unwrap_err();

        let expected_ks: Vec<_> = Vec::from(corrupted_ks_set);
        assert!(
            matches!(result, QueryError::ValidationFailed(ref responsible_ks)
                if responsible_ks == &expected_ks),
            "Should have found corrupted ks {expected_ks:?}, found {result:?}"
        );
    }

