    #[derive(Clone, Debug)]
    struct Dna(String);

    impl Arbitrary for Dna {
        fn arbitrary(g: &mut Gen) -> Self {
            // Using Vec::arbitrary(g) until g.gen_range(0..g.size()) is public
            let len = 3 * Vec::<()>::arbitrary(g).len();
            let dna = (0..len)
                .filter_map(|_| g.choose(&['a', 'c', 'g', 't']))
                .collect();
            Self(dna)
        }
    }

    fn random_populated_subset(
        rng: &mut (impl RngCore + CryptoRng),
        keyservers: &KeyserverIdSet,
    ) -> KeyserverIdSet {
        let subset_size = rng.gen_range(1..keyservers.len());
        let keyserver_ids = Vec::from(keyservers.clone());
        keyserver_ids
            .choose_multiple(rng, subset_size)
            .cloned()
            .collect()
    }

    fn hash_via_keyshares(
        rng: impl CryptoRng + RngCore,
        keyshares: &KeyShares,
        quorum_set: &KeyserverIdSet,
        padding: usize,
        windows: impl IntoIterator<Item: AsRef<[u8]>>,
    ) -> Result<Vec<CompressedCompletedHashValue>, QueryError> {
        let (queries, security_context) = setup_queries(rng, windows, padding, SECURITY_PARAMETER);
        let responses = keyshares.apply_keyshares(quorum_set, queries.iter().copied());
        security_context.recombine(&responses, &keyshares.active_security_key)
    }

    fn hash_via_key(
        key: &KeyShare,
        windows: impl IntoIterator<Item: AsRef<[u8]>>,
    ) -> Vec<CompressedCompletedHashValue> {
        windows
            .into_iter()
            .map(|window| {
                let rp = RistrettoPoint::hash_from_bytes::<Sha3_512>(window.as_ref());
                key.apply(Query::from_rp(rp)).compress().as_bytes().into()
            })
            .collect()
    }

    fn corrupt_hashpart(hash_part: &mut CompressedHashPart) {
        let mut bytes = *hash_part.as_bytes();
        bytes[0] = 0xff;
        *hash_part = CompressedHashPart::from(bytes);
    }

    // Quick sanity check... Run with -- --ignored to do more comprehensive tests
    #[test]
    fn distributed_keyshare_application_matches_single_key_application() {
        let mut rng = OsRng;

        let num_required_keyshares = 2..6;
        let num_additional_keys = 0..6;
        let keyshares = KeyShares::random(&mut rng, num_required_keyshares, num_additional_keys);
        let quorum_set = keyshares.random_quorum_set(&mut rng);
        let windows = [
            "foobar",
            "The five boxing wizards jump quickly.",
            "",
            "acgtacgtacgt",
            "xyzzy",
        ];
        let padding = 0;

        assert_eq!(
            hash_via_keyshares(rng, &keyshares, &quorum_set, padding, windows).unwrap(),
            hash_via_key(&keyshares.secret, windows),
        );
    }

    #[test]
    fn padding_does_not_affect_output_length() {
        let mut rng = OsRng;

        let num_required_keyshares = 2..6;
        let num_additional_keys = 0..6;
        let keyshares = KeyShares::random(&mut rng, num_required_keyshares, num_additional_keys);
        let quorum_set = keyshares.random_quorum_set(&mut rng);

        let windows = [
            "foobar",
            "The five boxing wizards jump quickly.",
            "",
            "acgtacgtacgt",
            "xyzzy",
        ];

        for padding in [0, 1, 2, 3, 8, 25] {
            let (queries, security_context) =
                setup_queries(rng, windows, padding, SECURITY_PARAMETER);
            let responses = keyshares.apply_keyshares(&quorum_set, queries.iter().copied());
            let hashes = security_context
                .recombine(&responses, &keyshares.active_security_key)
                .unwrap();
            assert_eq!(hashes.len(), windows.len());
        }
    }

    #[test]
    fn padding_increases_size_of_response() {
        let windows = ["foo", "bar", "baz"];
        // Rather that testing against particular numbers of queries, which would heavily couple
        // this test to Verifier details, we check that padding increases the number of queries
        // by the specified amount.
        let paddings = [0, 1, 2, 3, 8, 25];
        let lens = paddings.map(|padding| {
            let (queries, _) = setup_queries(OsRng, windows, padding, SECURITY_PARAMETER);
            queries.len()
        });
        for (len, padding) in lens.into_iter().zip(paddings) {
            assert_eq!(len - lens[0], padding);
        }
    }

    #[test]
    fn queries_are_potentially_blinded() {
        let windows = ["foo", "bar", "baz"];
        let padding = 0;
        let (queries1, _) = setup_queries(OsRng, windows, padding, SECURITY_PARAMETER);
        let (queries2, _) = setup_queries(OsRng, windows, padding, SECURITY_PARAMETER);
        for (q1, q2) in queries1.iter().zip(queries2.iter()) {
            assert_ne!(q1.as_bytes(), q2.as_bytes());
        }
    }

    #[test]
    fn recombine_rejects_missing_responses() {
        let rng = &mut OsRng;
        let num_required_keyshares = 2..6;
        let num_additional_keys = 0..6;
        let keyshares = KeyShares::random(rng, num_required_keyshares, num_additional_keys);
        let quorum_set = keyshares.random_quorum_set(rng);
        let padding = 0;
        let windows = [""];

        let (queries, security_context) =
            setup_queries(&mut *rng, windows, padding, SECURITY_PARAMETER);
        let mut responses = keyshares.apply_keyshares(&quorum_set, queries.iter().copied());
        let bad_response_i = rng.gen_range(0..responses.len());
        responses.swap_remove(bad_response_i);
        let err = security_context
            .recombine(&responses, &keyshares.active_security_key)
            .unwrap_err();
        assert!(matches!(err, QueryError::MissingKeyserverResponse));
    }

