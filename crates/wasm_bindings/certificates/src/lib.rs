pub fn get_cert_info<R: Role>(cert_pem: String) -> Result<JsValue, String> {
    let cert_bundle = cert_from_pem::<R>(cert_pem)?;
    let cert = cert_bundle
        .get_lead_cert(&SystemClock)
        .map_err(|e| format!("Failed to get lead cert: {e}"))?;
    let cert_info = CertInfo {
        all_emails_to_notify: cert.all_emails_to_notify(),
    };
    to_js(&cert_info)
}

pub fn check_cert<R: Role>(
    cert_pem: String,
    priv_pem: String,
    priv_passphrase: String,
) -> Result<JsValue, String> {
    let cert_bundle = cert_from_pem::<R>(cert_pem)?;
    let result = precheck_key::<R>(&cert_bundle, &priv_pem, &priv_passphrase, &SystemClock);
    to_js(&result)
}

