#[wasm_bindgen]
pub fn check_ecies_private_key(
    esr_pem: String,
    ecies_pem: String,
    ecies_passphrase: String,
) -> Result<JsValue, String> {
    let _ = decrypt_encrypted_screening_response(esr_pem, ecies_pem, ecies_passphrase)?;
    to_js(&())
}

/// The result of this function is a list of bytes, which *should* be valid
/// JSON, but to keep this wrapper light and flexible, we'll leave the
/// JSON-parsing work for the web interface to do.
#[wasm_bindgen]
pub fn decrypt_encrypted_screening_response(
    esr_pem: String,
    ecies_pem: String,
    ecies_passphrase: String,
) -> Result<Vec<u8>, String> {
    let kp = ecies_keypair_from_pem(ecies_pem, ecies_passphrase)?;
    let encrypted = bytes_from_pem(
        &esr_pem,
        "SECUREDNA ENCRYPTED SCREENING RESPONSE".to_owned(),
    )
    .map_err(|_| "Not a valid encrypted screening response".to_owned())?;
    kp.decrypt(encrypted).map_err(|_| {
        "Failed to decrypt screening response. (Are you using the right keypair?)".to_owned()
    })
}

#[wasm_bindgen]
pub fn extract_data_from_existing_synth_token(
    synth_token_pem: String,
) -> Result<IDataFromExistingSynthToken, String> {
    let st = token_bundle_from_pem::<SynthesizerTokenGroup>(synth_token_pem)?;

    let data = DataFromExistingSynthToken {
        domain: st.token.manufacturer_domain().to_owned(),
        model: st.token.model().to_owned(),
        serial: st.token.serial_number().to_owned(),
        rate_limit: st.token.max_dna_base_pairs_per_day(),
        audit_email: st.token.audit_email().map(|a| a.to_string()),
        audit_public_key_pem: st.token.audit_email_public_key().map(|a| a.to_string()),
    };

    to_js(&data)
}
