#[wasm_bindgen]
pub fn create_synthesizer_token(
    body: ICreateSynthesizerToken,
) -> Result<ISynthesizerTokenFiles, String> {
    let CreateSynthesizerToken {
        domain,
        model,
        serial,
        rate_limit,
        audit_email,
        audit_passphrase,
        token_passphrase,
        cert_pem,
        cert_private_key_pem,
        cert_passphrase,
        days_valid,
        existing_audit_pub_pem,
    } = serde_wasm_bindgen::from_value(body.into())
        .map_err(|e| format!("Couldn't decode JSON: {e:?}"))?;

    let keypair = load_key(cert_private_key_pem, cert_passphrase)?;
    let cert_bundle = cert_from_pem(cert_pem)?;

    let mut new_audit_private_key_pem: Option<String> = None;

    let audit_recipient = match (audit_email, audit_passphrase, existing_audit_pub_pem) {
        (None, None, None) => Ok(None),
        (Some(email), Some(passphrase), None) => {
            let kp = EciesKeyPair::new_random();
            let mut priv_pem_bytes: Vec<u8> = vec![];
            kp.write_key(&mut priv_pem_bytes, passphrase)
                .map_err(|_| "Couldn't encrypt private key".to_owned())?;
            let priv_pem = String::from_utf8(priv_pem_bytes)
                .map_err(|_| "Invalid UTF-8 in private key".to_owned())?;
            new_audit_private_key_pem = Some(priv_pem);
            Ok(Some(AuditRecipient::new(email, kp.public_key())))
        }
        (Some(email), None, Some(existing_pub_pem)) => {
            let public_key = existing_pub_pem
                .parse()
                .map_err(|_| "Audit key parse error".to_owned())?;
            Ok(Some(AuditRecipient::new(email, public_key)))
        }
        (None, _, _) => Err("Missing audit email".to_owned()),
        (Some(_), None, None) => {
            Err("Missing audit public key or passphrase for new key".to_owned())
        }
        (Some(_), _, _) => {
            Err("Both audit public key and passphrase for new key were given".to_owned())
        }
    }?;

    let domain = Domain::try_new(domain).map_err(|e| e.to_string())?;

    let token_keypair = SigningKeyPair::new_random();
    let token_request = SynthesizerTokenRequest::v1_token_request(
        token_keypair.public_key(),
        domain,
        model,
        serial,
        rate_limit,
        audit_recipient,
    );
    let token_kp_pem = keypair_to_pem(token_keypair, token_passphrase)?;

    let expiration = Expiration::expiring_in_days(days_valid)
        .map_err(|e| format!("Invalid expiration: {e:?}"))?;

    let token_bundle = cert_bundle
        .issue_synthesizer_token_bundle(token_request, expiration, keypair)
        .map_err(|_| "Failed to issue token bundle".to_owned())?;

    let files = SynthesizerTokenFiles {
        private_key_pem: token_kp_pem.private_key_pem,
        synthesizer_token_pem: token_bundle
            .to_file_contents()
            .map_err(|_| "Couldn't make synth token pem".to_owned())?,
        new_audit_private_key_pem,
    };
    to_js(&files)
}

#[wasm_bindgen]
pub fn subset_et(
    et_pem: Vec<u8>,
    etr_pem: Vec<u8>,
    priv_pem: Vec<u8>,
    priv_passphrase: Vec<u8>,
    validity_days: u32,
) -> Result<Vec<u8>, String> {
    let et_bundle = token_bundle_from_pem::<ExemptionTokenGroup>(et_pem)?;
    let etr = etr_from_pem(etr_pem)?;
    let keypair = load_key(priv_pem, priv_passphrase)?;
    let expiration = Expiration::expiring_in_days(validity_days as i64)
        .map_err(|e| format!("Invalid expiration: {e:?}"))?;
    let sub_et = et_bundle
        .issue_exemption_token_bundle(
            etr,
            expiration,
            et_bundle.token.issuer_auth_devices().to_vec(),
            keypair,
        )
        .map_err(|e| format!("Failed to issue subset exemption token: {e:?}"))?;
    let sub_et_pem = sub_et
        .to_file_contents()
        .map_err(|e| format!("Couldn't encode exemption token: {e:?}"))?;

    Ok(sub_et_pem.into_bytes())
}

